/** FEN after playing `moves` (SAN) from the initial position – for puzzles taken from opening traps. */
function after(...moves: string[]): string {
  const g = ChessGame.fromFen(START_FEN);
  for (const m of moves) if (!g.move(m)) throw new Error(`illegal opening move ${m}`);
  return g.fen();
}

