import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { GameResult } from './selfplay';
import { createAccumulator } from './index';
import { uciLineToSan } from '@/lib/chess';
const dir = process.argv[2]!;
const files = readdirSync(dir).sort((a, b) => Number(a.match(/\d+/)![0]) - Number(b.match(/\d+/)![0]));
const acc = createAccumulator(1e9, []);
for (const f of files) acc.add(JSON.parse(readFileSync(join(dir, f), 'utf8')) as GameResult);
const n = Number(process.argv[3] ?? 40);
for (const p of acc.generated.slice(0, n)) console.log(p.rating, uciLineToSan(p.fen, p.moves).join(' '), '|', p.themes.join(','), '|', p.explanation!.plain);
console.log(acc.counters, acc.generated.length);
console.log(acc.stats().bands);
import { checkPuzzleStructure } from '../lib/puzzleChecks';
const w: Record<string, number> = {};
for (const p of acc.generated) for (const x of checkPuzzleStructure(p).warnings) w[x.message] = (w[x.message] ?? 0) + 1;
console.log('warnings', w);
